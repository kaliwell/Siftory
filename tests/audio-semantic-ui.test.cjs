const assert = require('node:assert/strict')
const fs = require('node:fs')
const test = require('node:test')

test('audio semantic batch build is restorable across renderer, preload, IPC, and packaging', () => {
  const component = fs.readFileSync('src/components/AudioSemanticStatusCard.tsx', 'utf8')
  const preload = fs.readFileSync('electron/preload.ts', 'utf8')
  const ipc = fs.readFileSync('electron/mediaSearchIpc.ts', 'utf8')
  const mediaPanel = fs.readFileSync('src/components/MediaSearchPanel.tsx', 'utf8')
  const worker = fs.readFileSync('electron/audioSemanticBuildChild.ts', 'utf8')
  const vite = fs.readFileSync('vite.config.mjs', 'utf8')
  const packageJson = JSON.parse(fs.readFileSync('package.json', 'utf8'))

  assert.match(component, /audio-semantic-progress/)
  assert.match(component, /startAudioSemanticBuild/)
  assert.match(component, /stopAudioSemanticBuild/)
  assert.match(component, /resumeAudioSemanticBuild/)
  assert.match(component, /selectedVideoId/)
  assert.match(component, /setInterval/)
  assert.match(component, /activelyBuilding \? 3_000 : status\?\.statsPending \? 1_000 : 15_000/)
  assert.match(component, /refresh\(true\)/)
  assert.match(mediaPanel, /<AudioSemanticStatusCard[^>]+videos=\{videos\}/)
  assert.match(preload, /mediaSearch:startAudioSemanticBuild/)
  assert.match(preload, /mediaSearch:stopAudioSemanticBuild/)
  assert.match(preload, /mediaSearch:resumeAudioSemanticBuild/)
  assert.match(ipc, /ELECTRON_RUN_AS_NODE/)
  assert.match(ipc, /FLOATING_CLOCK_RESOURCES_PATH/)
  assert.match(ipc, /FLOATING_CLOCK_SENSEVOICE_RUNTIME_ROOT/)
  assert.match(ipc, /FLOATING_CLOCK_SENSEVOICE_RUNNER_PATH/)
  assert.match(ipc, /sourceFingerprint/)
  assert.match(ipc, /app-restarted/)
  assert.match(ipc, /AUDIO_SEMANTIC_STATIC_STATUS_CACHE_MS = 30_000/)
  assert.match(ipc, /getAudioSemanticUiStatusWithRefresh\(rawForceRefresh === true\)/)
  assert.match(ipc, /getAudioSemanticTranscriptStatsSnapshot/)
  assert.match(worker, /saveAudioSemanticTranscript/)
  assert.match(worker, /PersistentAudioSpeakerClusterer/)
  assert.match(worker, /inspectDiarization/)
  assert.match(worker, /\.diarize\(/)
  assert.match(worker, /markStopped/)
  assert.match(vite, /audioSemanticBuildChild\.js/)
  assert.ok(
    packageJson.build.extraResources.some(
      (entry) => entry.from === 'dist-electron/audioSemanticBuildChild.js',
    ),
  )
})
