const fs = require('node:fs')
const path = require('node:path')

function packageNameFromLockPath(lockPath, metadata = {}) {
  if (typeof metadata.name === 'string' && metadata.name.trim()) return metadata.name.trim()
  const marker = 'node_modules/'
  const index = lockPath.lastIndexOf(marker)
  return index >= 0 ? lockPath.slice(index + marker.length) : lockPath
}

function normalizeLicense(value) {
  if (typeof value === 'string' && value.trim()) return value.trim()
  if (Array.isArray(value)) {
    const values = value.map(normalizeLicense).filter((entry) => entry !== 'NOASSERTION')
    if (values.length > 0) return values.join(' OR ')
  }
  if (value && typeof value.type === 'string') return normalizeLicense(value.type)
  return 'NOASSERTION'
}

function normalizeRepository(manifest = {}) {
  const raw = typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url
  const value = raw || manifest.homepage || ''
  return String(value).replace(/^git\+/, '').replace(/\.git(?:#.*)?$/, '')
}

function collectNodeComponents(projectRoot) {
  const lock = JSON.parse(fs.readFileSync(path.join(projectRoot, 'package-lock.json'), 'utf8'))
  const components = []
  for (const [lockPath, metadata] of Object.entries(lock.packages || {})) {
    if (!lockPath || metadata.dev === true || !lockPath.includes('node_modules/')) continue
    let installed = {}
    try {
      installed = JSON.parse(
        fs.readFileSync(path.join(projectRoot, lockPath, 'package.json'), 'utf8'),
      )
    } catch {
      /* The lockfile remains authoritative when an optional package is absent locally. */
    }
    components.push({
      name: packageNameFromLockPath(lockPath, installed),
      version: metadata.version || installed.version || 'unknown',
      license: normalizeLicense(metadata.license || installed.license || installed.licenses),
      repository: normalizeRepository(installed),
      optional: metadata.optional === true,
      os: Array.isArray(metadata.os) ? metadata.os.join(', ') : '',
      cpu: Array.isArray(metadata.cpu) ? metadata.cpu.join(', ') : '',
    })
  }
  const unique = new Map()
  for (const component of components) {
    unique.set(`${component.name}@${component.version}`, component)
  }
  return [...unique.values()].sort((left, right) =>
    `${left.name}@${left.version}`.localeCompare(`${right.name}@${right.version}`),
  )
}

function escapeCell(value) {
  return String(value || '-').replaceAll('|', '\\|').replaceAll('\n', ' ')
}

function renderNodeComponents(components) {
  const rows = components
    .map(
      (component) =>
        `| ${escapeCell(component.name)} | ${escapeCell(component.version)} | ${escapeCell(component.license)} | ${component.optional ? 'yes' : 'no'} | ${escapeCell(component.os)} | ${escapeCell(component.cpu)} | ${escapeCell(component.repository)} |`,
    )
    .join('\n')
  return `# Node Production Dependency License Inventory

<!-- Generated by scripts/generate-node-third-party-components.cjs. Do not edit manually. -->

This lockfile-derived inventory covers non-development npm packages that may enter a packaged
Siftory application. Platform-specific optional packages can appear even when they are not selected
for the current Windows build. The release SBOM and unpacked-package scan remain authoritative for
the exact artifact. This inventory is evidence, not legal approval.

| Package | Version | Declared license | Optional | OS | CPU | Upstream |
| --- | --- | --- | --- | --- | --- | --- |
${rows}

Packages: ${components.length}  
Unresolved license declarations: ${components.filter((component) => component.license === 'NOASSERTION').length}
`
}

function main() {
  const projectRoot = path.resolve(__dirname, '..')
  const outputPath = path.join(projectRoot, 'NODE_THIRD_PARTY_COMPONENTS.md')
  const rendered = renderNodeComponents(collectNodeComponents(projectRoot))
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : ''
    if (current !== rendered) {
      console.error('Node production dependency license inventory is stale')
      process.exitCode = 1
      return
    }
    console.log('Node production dependency license inventory is current')
    return
  }
  fs.writeFileSync(outputPath, rendered, 'utf8')
  console.log(`Generated ${path.relative(projectRoot, outputPath)}`)
}

if (require.main === module) main()

module.exports = {
  collectNodeComponents,
  normalizeLicense,
  packageNameFromLockPath,
  renderNodeComponents,
}
