const fs = require('node:fs')
const path = require('node:path')

const projectRoot = path.resolve(__dirname, '..')
const manifestPath = path.join(projectRoot, 'resources', 'runtime-manifest.json')
const outputPath = path.join(projectRoot, 'THIRD_PARTY_COMPONENTS.md')

function escapeCell(value) {
  return String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ')
}

function renderThirdPartyComponents(manifest) {
  const components = [...(manifest.components || [])].sort((left, right) =>
    left.id.localeCompare(right.id),
  )
  const lines = [
    '# Bundled Third-Party Components',
    '',
    '<!-- Generated by scripts/generate-third-party-components.cjs. Do not edit manually. -->',
    '',
    `Manifest: \`${manifest.manifestId}\` schema ${manifest.schemaVersion}`,
    '',
    '| Component | Type | Upstream version | SPDX | Review status | Bundled | Artifacts |',
    '| --- | --- | --- | --- | --- | --- | ---: |',
  ]
  for (const component of components) {
    lines.push(
      `| ${escapeCell(component.upstream.name)} (\`${escapeCell(component.id)}\`) | ${escapeCell(component.componentType)} | ${escapeCell(component.upstream.version)} | ${escapeCell(component.license.spdx)} | ${escapeCell(component.license.reviewStatus)} | ${component.distribution.defaultBundled ? 'yes' : 'no'} | ${component.artifacts.length} |`,
    )
  }
  lines.push(
    '',
    'This inventory is generated from `resources/runtime-manifest.json`. It records engineering provenance only; entries marked `legal-review-required` or `project-license-pending` are not approved for public or commercial distribution.',
    '',
  )
  return lines.join('\n')
}

function main() {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
  const rendered = renderThirdPartyComponents(manifest)
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : ''
    if (current !== rendered) {
      console.error('THIRD_PARTY_COMPONENTS.md is missing or out of date')
      process.exitCode = 1
      return
    }
    console.log(`Third-party component inventory is current (${manifest.components.length} components)`)
    return
  }
  fs.writeFileSync(outputPath, rendered, 'utf8')
  console.log(`Generated ${path.relative(projectRoot, outputPath)} (${manifest.components.length} components)`)
}

if (require.main === module) main()

module.exports = { renderThirdPartyComponents }
