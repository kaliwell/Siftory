export function normalizeLanguage(value: unknown): AppLanguage | null {
  if (typeof value !== 'string') return null
  const normalized = value.trim().toLowerCase()
  if (normalized === 'zh' || normalized.startsWith('zh-')) return 'zh-CN'
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en'
  return null
}

export function detectSystemLanguage(languages?: readonly string[]): AppLanguage {
  const candidates =
    languages ??
    (typeof navigator === 'undefined'
      ? []
      : navigator.languages?.length
        ? navigator.languages
        : [navigator.language])
  for (const candidate of candidates) {
    const language = normalizeLanguage(candidate)
    if (language) return language
  }
  return 'en'
}

export function translate(language: AppLanguage, key: string, values?: TranslationValues): string {
  const template = language === 'zh-CN' ? (zhCN[key] ?? key) : (enUS[key] ?? key)
  if (!values) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
  )
}
